//! Public-API tests for the fish completion generator.
//!
//! Covers script structure, global and command flags, subcommand dispatch,
//! the depth cap and unbounded-condition handling, the short-flag byte guard
//! (F7-01), and hostile-name hardening. All tests exercise the generator
//! exclusively through its public API (`generate`). The escaper-family unit
//! tests (escapeFishSingleQuote) remain inline in fish.zig. Extracted to
//! satisfy the 800-line file-size gate, following the bash_test.zig /
//! zsh_test.zig precedent.

