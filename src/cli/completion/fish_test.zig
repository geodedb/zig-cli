test "fish: printable-but-non-alphanumeric short flag byte is dropped (F7-01)" {
    // A `;` short flag would emit `-s ;`, terminating the `complete` command
    // early and injecting whatever follows. It is printable, so the old
    // isPrint guard let it through. The `-l 'name'` long option must still be
    // emitted so the completion line stays valid.
    const cmd = Command{
        .name = "myapp",
        .summary = "My application",
        .flags = &.{
            command.FlagSpec{
                .name = "name",
                .short = ';',
                .help = "hostile short",
                .ftype = .bool,
            },
        },
    };

    const script = try generate(&cmd, std.testing.allocator);
    defer std.testing.allocator.free(script);

    // No `-s ;` fragment may appear.
    try std.testing.expect(std.mem.indexOf(u8, script, "-s ;") == null);
    try std.testing.expect(std.mem.indexOfScalar(u8, script, ';') == null);
    // The long option is still emitted (completion line remains valid).
    try std.testing.expect(std.mem.indexOf(u8, script, "-l 'name'") != null);
}

