test "fish: hostile root name with single-quote is escaped in complete -c (gap A)" {
    // cmd.name = "app'x" — the single-quote must be escaped in the emitted
    // `complete -c 'NAME'` lines; the raw breakout form must not appear.
    const cmd = Command{
        .name = "app'x",
        .summary = "Hostile name",
    };

    const script = try generate(&cmd, std.testing.allocator);
    defer std.testing.allocator.free(script);

    // Escaped form must appear (fish single-quote escape: \')
    try std.testing.expect(std.mem.indexOf(u8, script, "complete -c 'app\\'x'") != null);
    // Raw unescaped breakout must NOT appear
    try std.testing.expect(std.mem.indexOf(u8, script, "complete -c app'x") == null);
    try std.testing.expect(std.mem.indexOf(u8, script, "complete -c 'app'x") == null);
}

