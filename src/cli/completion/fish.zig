//! # Fish Completion Module
//!
//! Generates fish shell completion scripts for CLI commands with full
//! support for nested subcommands.

const std = @import("std");
const command = @import("../command.zig");
const Command = command.Command;
const FlagSpec = command.FlagSpec;

/// Maximum subcommand nesting depth for generated completions.
/// Levels beyond this are skipped rather than written out of bounds.
const max_depth = 16;

/// Escape a string for use inside fish single-quoted contexts.
/// Escapes: ' as \', \ as \\
/// Strips: NUL bytes (0x00), newlines (0x0A), carriage returns (0x0D).
/// Fast path: if no special chars, returns `s` directly (no allocation).
pub fn escapeFishSingleQuote(allocator: std.mem.Allocator, s: []const u8) ![]const u8 {
    var needs_escape = false;
    for (s) |c| {
        switch (c) {
            '\'', '\\', 0x00, '\n', '\r' => {
                needs_escape = true;
                break;
            },
            else => {},
        }
    }
    if (!needs_escape) return s;

    var list: std.ArrayListUnmanaged(u8) = .empty;
    list.ensureTotalCapacity(allocator, s.len) catch {};
    for (s) |c| {
        switch (c) {
            // Strip NUL bytes and newlines entirely
            0x00, '\n', '\r' => {},
            '\'', '\\' => {
                list.append(allocator, '\\') catch return error.OutOfMemory;
                list.append(allocator, c) catch return error.OutOfMemory;
            },
            else => {
                list.append(allocator, c) catch return error.OutOfMemory;
            },
        }
    }
    return list.toOwnedSlice(allocator);
}

/// Generate fish completion script
pub fn generate(cmd: *const Command, allocator: std.mem.Allocator) ![]const u8 {
    var arena = std.heap.ArenaAllocator.init(allocator);
    defer arena.deinit();
    // esc_alloc MUST be arena-backed: escaper and condition-builder results
    // are never individually freed.
    const esc_alloc = arena.allocator();

    var buf: std.Io.Writer.Allocating = .init(allocator);
    errdefer buf.deinit();
    buf.ensureUnusedCapacity(4096) catch {};
    const w = &buf.writer;

    try w.print("# Fish completion for {s}\n", .{cmd.name});
    try w.print("# Generated by zig-cli\n\n", .{});

    // Escape the root command name once; all `complete -c 'NAME'` emissions use this.
    const esc_root_name = try escapeFishSingleQuote(esc_alloc, cmd.name);

    // Disable file completion by default
    try w.print("complete -c '{s}' -f\n\n", .{esc_root_name});

    // Generate completions for all commands recursively
    try generateCommandCompletions(w, cmd, esc_root_name, &.{}, esc_alloc);

    return buf.toOwnedSlice();
}

/// Generate completions for a command and its subcommands recursively.
/// `root_name` must be the already-escaped (via escapeFishSingleQuote) command
/// name so every `complete -c 'NAME'` emission is safe.
fn generateCommandCompletions(w: anytype, cmd: *const Command, root_name: []const u8, path: []const []const u8, esc_alloc: std.mem.Allocator) !void {
    // Build condition for this command level
    const condition = try buildCondition(path, cmd, esc_alloc);

    // Section header
    if (path.len == 0) {
        try w.print("# Global flags\n", .{});
    } else {
        try w.print("# Flags for: {s}", .{path[0]});
        for (path[1..]) |p| {
            try w.print(" {s}", .{p});
        }
        try w.print("\n", .{});
    }

    // Global flags (only at root level, sourced from canonical command.global_flags)
    if (path.len == 0) {
        for (command.global_flags) |*gflag| {
            try w.print("complete -c '{s}'", .{root_name});
            if (gflag.short) |s| {
                try w.print(" -s {c}", .{s});
            }
            const esc_gname = try escapeFishSingleQuote(esc_alloc, gflag.name);
            try w.print(" -l '{s}'", .{esc_gname});
            const esc_ghelp = try escapeFishSingleQuote(esc_alloc, gflag.help);
            try w.print(" -d '{s}'\n", .{esc_ghelp});
        }
        try w.writeAll("\n");
    }

    // Command-specific flags
    if (cmd.flags.len > 0) {
        for (cmd.flags) |*flag| {
            try w.print("complete -c '{s}'", .{root_name});
            if (condition.len > 0) {
                try w.print(" -n '{s}'", .{condition});
            }
            if (flag.short) |s| {
                try w.print(" -s {c}", .{s});
            }
            const esc_fname = try escapeFishSingleQuote(esc_alloc, flag.name);
            try w.print(" -l '{s}'", .{esc_fname});
            if (flag.ftype != .bool) {
                try w.print(" -r", .{}); // Requires argument
                // Add value completions if available
                if (flag.completions.len > 0) {
                    try w.writeAll(" -a '");
                    for (flag.completions, 0..) |val, i| {
                        if (i > 0) try w.writeAll(" ");
                        const esc_val = try escapeFishSingleQuote(esc_alloc, val);
                        try w.print("{s}", .{esc_val});
                    }
                    try w.writeAll("'");
                } else if (flag.ftype == .path) {
                    try w.writeAll(" -F"); // File completion
                }
            }
            const esc_flag_help = try escapeFishSingleQuote(esc_alloc, flag.help);
            try w.print(" -d '{s}'\n", .{esc_flag_help});
        }
        try w.print("\n", .{});
    }

    // Subcommands
    if (cmd.subcommands.len > 0) {
        if (path.len == 0) {
            try w.print("# Subcommands\n", .{});
        } else {
            try w.print("# Subcommands for: {s}", .{path[0]});
            for (path[1..]) |p| {
                try w.print(" {s}", .{p});
            }
            try w.print("\n", .{});
        }

        // Build condition for showing subcommands at this level
        const subcmd_condition = try buildSubcommandCondition(path, cmd, esc_alloc);

        for (cmd.subcommands) |subcmd| {
            if (!subcmd.hidden) {
                try w.print("complete -c '{s}'", .{root_name});
                if (subcmd_condition.len > 0) {
                    try w.print(" -n '{s}'", .{subcmd_condition});
                }
                const esc_name = try escapeFishSingleQuote(esc_alloc, subcmd.name);
                const esc_summary = try escapeFishSingleQuote(esc_alloc, subcmd.summary);
                try w.print(" -a '{s}' -d '{s}'\n", .{ esc_name, esc_summary });
            }
        }
        try w.print("\n", .{});

        // Recursively generate completions for subcommands
        for (cmd.subcommands) |subcmd| {
            if (!subcmd.hidden) {
                // Depth cap: completions are generated at most max_depth levels
                // deep (documented limit). Deeper trees are skipped, never an
                // out-of-bounds stack write (CWE-787).
                if (path.len >= max_depth) break;
                // Build new path (limit: max_depth levels of subcommand nesting)
                var new_path: [max_depth][]const u8 = undefined;
                var new_path_len: usize = 0;
                for (path) |p| {
                    new_path[new_path_len] = p;
                    new_path_len += 1;
                }
                new_path[new_path_len] = subcmd.name;
                new_path_len += 1;

                try generateCommandCompletions(w, subcmd, root_name, new_path[0..new_path_len], esc_alloc);
            }
        }
    }
}

/// Build the fish condition for flag completions at a command level.
/// Path elements and subcommand names are escaped for use in single-quoted contexts.
/// The result is allocated from `esc_alloc`, which MUST be arena-backed
/// (results are never individually freed); allocation makes the condition
/// length unbounded — a fixed buffer here used to silently truncate long
/// conditions to "", dropping the -n guard entirely.
fn buildCondition(path: []const []const u8, cmd: *const Command, esc_alloc: std.mem.Allocator) ![]const u8 {
    if (path.len == 0) {
        return "";
    }

    // Condition: must have seen all commands in path, and not yet any of the subcommands
    var aw: std.Io.Writer.Allocating = .init(esc_alloc);
    const w = &aw.writer;

    // Must have seen all parent commands
    try w.print("__fish_seen_subcommand_from", .{});
    for (path) |p| {
        const esc_p = try escapeFishSingleQuote(esc_alloc, p);
        try w.print(" {s}", .{esc_p});
    }

    // Must not have started any subcommand yet
    if (cmd.subcommands.len > 0) {
        try w.print("; and not __fish_seen_subcommand_from", .{});
        for (cmd.subcommands) |subcmd| {
            if (!subcmd.hidden) {
                const esc_name = try escapeFishSingleQuote(esc_alloc, subcmd.name);
                try w.print(" {s}", .{esc_name});
            }
        }
    }

    return aw.toOwnedSlice();
}

/// Build the fish condition for showing subcommands at a command level.
/// Path elements and subcommand names are escaped for use in single-quoted contexts.
/// The result is allocated from `esc_alloc`, which MUST be arena-backed
/// (results are never individually freed); see buildCondition for why a
/// fixed buffer is not used.
fn buildSubcommandCondition(path: []const []const u8, cmd: *const Command, esc_alloc: std.mem.Allocator) ![]const u8 {
    if (path.len == 0) {
        // Root level: use __fish_use_subcommand
        return "__fish_use_subcommand";
    }

    // Nested level: must have seen parent commands, not yet any subcommands
    var aw: std.Io.Writer.Allocating = .init(esc_alloc);
    const w = &aw.writer;

    // Must have seen all parent commands
    try w.print("__fish_seen_subcommand_from", .{});
    for (path) |p| {
        const esc_p = try escapeFishSingleQuote(esc_alloc, p);
        try w.print(" {s}", .{esc_p});
    }

    // Must not have started any subcommand yet
    if (cmd.subcommands.len > 0) {
        try w.print("; and not __fish_seen_subcommand_from", .{});
        for (cmd.subcommands) |subcmd| {
            if (!subcmd.hidden) {
                const esc_name = try escapeFishSingleQuote(esc_alloc, subcmd.name);
                try w.print(" {s}", .{esc_name});
            }
        }
    }

    return aw.toOwnedSlice();
}

